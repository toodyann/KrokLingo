// JS \b and \w only know ASCII letters: rewrite them to Unicode-aware forms (with the u flag)
const UB = '(?:(?<=\\p{L})(?!\\p{L})|(?<!\\p{L})(?=\\p{L}))'
const cache = new Map()
function uk(re, global = false) {
  const key = re.source + re.flags + global
  if (!cache.has(key)) {
    const source = re.source.replace(/\\b/g, UB).replace(/\\w/g, '\\p{L}')
    cache.set(key, new RegExp(source, 'u' + (re.flags.includes('i') ? 'i' : '') + (global ? 'g' : '')))
  }
  return cache.get(key)
}

// line-break hyphens split words ("ендо- метрію"); classification sees them joined
const dehyphen = (s) => s.replace(/(\p{Ll})- (?!та\b|і\b|й\b|або\b)(\p{Ll})/gu, '$1$2')

function scoresUk(item) {
  item = { text: dehyphen(item.text), options: item.options.map(dehyphen) }
  const text = (item.text + ' || ' + item.options.join(' | ')).toLowerCase()
  const s = {}
  for (const t of ORDER) {
    let v = 0
    for (const re of K[t]) {
      const m = text.match(uk(re, true))
      if (m) v += Math.min(m.length, 3)
    }
    s[t] = v
  }
  // what is being asked (the stem's last sentence)
  const ask = (item.text.split(/(?<=[.?!:])\s+/).pop() || item.text.slice(-160)).toLowerCase()
  const bump = (topic, re, w) => {
    if (uk(re).test(ask)) s[topic] += w
  }
  bump('pharmacology', /як(ий|ого|им) (препарат|засіб|засоб|лікарськ)|препарат вибору|механізм дії|антидот|признач|застосувати|ввести/, 4)
  bump('biochemistry', /як(ий|ого|ої|а) (фермент|вітамін|кофермент|амінокислот|речовин|сполук)|нестач\w* (якого|якої)|порушення (синтезу|обміну|утворення)/, 3)
  bump('microbiology', /збудник|як(і|ий) (мікроорганізм|бактері|вірус|гриб)|яки[йм] методом|яку реакцію|поживн\w* середовищ|метод\w* (фарбуван|діагностик)/, 4)
  bump('biology', /як(ий|ого) (гельмінт|паразит|найпростіш)|гельмінтоз|тип\w* успадкуван|імовірн|ймовірн|каріотип|хромосом/, 4)
  bump('anatomy', /як(ий|ого|а|і|ої) (нерв|м'яз|артері|вен|кістк|отвір|лімфатичн|гілк|частин|відділ)|пошкоджен|ушкоджен|травмован/, 3)
  bump('histology', /як(і|ий|а) (клітин|тканин|епітелі|структур)|що це за клітин|(в|у|на) (мікро)?препараті|провізорн|зародков/, 4)
  bump('pathology', /як(ий|ого|е|а) (патологічн|процес|вид|тип|форм|різновид|ускладнен|захворюван|діагноз)|патогенез|механізм\w* розвитку|провідн\w* ланк|найбільш імовірн\w* (причин|діагноз)/, 3)
  bump('physiology', /як(і|а|ий|е) змін|що (відбудеться|зміниться)|збільшиться|зменшиться|як(ий|і) рефлекс|як(і|ий) рецептор|як(ий|ого) гормон/, 2)

  // what kind of answers are offered
  const opts = item.options.map((o) => o.toLowerCase())
  const share = (re) => opts.filter((o) => uk(re).test(o)).length
  const byType = [
    ['anatomy', /нерв|артері|\bвен(а|и)\b|м'яз|кістк|отвір|ганглі|вузол|зв'язк|протока|пазух|гілк|\b(a|n|m|v)\.\s?[a-z]/i],
    ['pathology', /(ит|оз|ома|емія|урія|патія|плазія|трофія)\b|недостатн|некроз|запален|набряк|тромбоз|емболі|інфаркт|гіпокс|жовтяниц|анемі|шок|синдром|хвороб/],
    ['microbiology', /кок\b|коки|бацил|клостриді|мікобактері|коринебактері|сальмонел|шигел|ешерихі|нейсері|трепонем|кандид|актиноміц|вірус|вібріон|паличк|рикетсі|хламіді|мікоплазм|борелі|лептоспір/],
    ['pharmacology', /міцин|циклін|флоксацин|азол\b|олол\b|прил\b|каїн\b|азепам|профен|фенак|препарат|блокатор|агоніст|антагоніст|інгібітор|анальгетик|антибіотик|діуретик/],
    ['biochemistry', /аза\b|ази\b|кислот|вітамін|кофермент|глюкоз|глікоген|холестерин|ліпопротеїн|сечовин|аміак|білірубін|гемоглобін|фосфат|лактат|піруват|кетон/],
    ['histology', /цит(и|ів)?\b|бласт(и|ів)?\b|класт|епітелі|тканин|клітин|волокн|шар\b|мембран|гранул|органел/],
  ]
  for (const [topic, re] of byType) {
    const n = share(re)
    if (n >= 3) s[topic] += 4
    else if (n === 2) s[topic] += 2
  }
  return s
}

/** Cyrillic «і» for the Latin "i" some booklet fonts produce; one apostrophe; option letters in Latin. */
function normalizeUk(s) {
  return s
    .replace(/[’ʼ`]/g, "'")
    .replace(/[\p{L}']+/gu, (w) => (/[Ѐ-ӿ]/.test(w) ? w.replace(/i/g, 'і').replace(/I/g, 'І') : w))
    .replace(/(^|[\s(«"])i(?=[\s,.)»"]|$)/g, (m, p, off, str) => {
      // a lone "i" between Cyrillic words is the conjunction «і»
      const around = str.slice(Math.max(0, off - 12), off + 14)
      return /[Ѐ-ӿ]/.test(around) ? p + 'і' : m
    })
}

