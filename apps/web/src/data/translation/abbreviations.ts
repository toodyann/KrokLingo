function parse(raw: string) {
  const exact = new Map<string, string>()
  const folded = new Map<string, string>()
  for (const line of raw.split('\n')) {
    const i = line.indexOf('|')
    if (i <= 0) continue
    const k = line.slice(0, i).trim()
    const v = line.slice(i + 1).trim()
    exact.set(k, v)
    if (!folded.has(k.toLowerCase())) folded.set(k.toLowerCase(), v)
  }
  return { exact, folded }
}

const { exact, folded } = parse(RAW)

export function lookupAbbreviation(token: string): string | undefined {
  return exact.get(token) ?? folded.get(token.toLowerCase())
}
